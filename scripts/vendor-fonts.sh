#!/usr/bin/env bash
# Downloads the openly licensed (SIL OFL) fonts used by the slide themes explored in
# slides/themes_explainer.nim from npm (@fontsource packages) into docs/assets/fonts,
# with their licenses and one fonts.css of @font-face rules, so no font CDN is needed.
# The vendored files are committed: rerun only to change fonts or versions.
#
# usage: scripts/vendor-fonts.sh   (needs npm)
set -euo pipefail

# package  css family  weights  styles
FONTS="
germania-one|Germania One|400|normal
alegreya|Alegreya|400 700|normal italic
pixelify-sans|Pixelify Sans|400 700|normal
im-fell-english|IM Fell English|400|normal italic
im-fell-english-sc|IM Fell English SC|400|normal
courier-prime|Courier Prime|400 700|normal
space-grotesk|Space Grotesk|400 700|normal
spectral|Spectral|400 700|normal italic
jetbrains-mono|JetBrains Mono|400 700|normal
"

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/docs/assets/fonts"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
rm -rf "$out"
mkdir -p "$out"
css="$out/fonts.css"
echo "/* generated by scripts/vendor-fonts.sh: SIL OFL fonts from @fontsource */" > "$css"

while IFS='|' read -r pkg family weights styles; do
  [ -z "$pkg" ] && continue
  mkdir -p "$tmp/$pkg" "$out/$pkg"
  (cd "$tmp/$pkg" && npm pack --silent "@fontsource/$pkg" >/dev/null && tar xzf ./*.tgz)
  cp "$tmp/$pkg/package/LICENSE" "$out/$pkg/LICENSE"
  for w in $weights; do
    for s in $styles; do
      f="$pkg-latin-$w-$s.woff2" # the latin subset is enough for the slides
      cp "$tmp/$pkg/package/files/$f" "$out/$pkg/"
      printf '@font-face { font-family: "%s"; font-style: %s; font-weight: %s; font-display: block; src: url(%s/%s) format("woff2"); }\n' \
        "$family" "$s" "$w" "$pkg" "$f" >> "$css"
    done
  done
done <<< "$FONTS"
ls "$out"
